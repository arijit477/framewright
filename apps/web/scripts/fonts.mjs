// Generates src/render/font-files.ts from the @fontsource packages' CSS: one
// entry per font file, with its unicode range, so workers can load exactly the
// files a title needs (workers can't use CSS @font-face).
//
//   pnpm fonts   (then formats the output with Prettier)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
/** Our font family → its package and stylesheets (normal, then italic if any). */
const FAMILIES = {
  sans: { pkg: '@fontsource-variable/inter', css: ['wght.css', 'wght-italic.css'] },
  serif: { pkg: '@fontsource-variable/playfair-display', css: ['wght.css', 'wght-italic.css'] },
  mono: { pkg: '@fontsource-variable/jetbrains-mono', css: ['wght.css', 'wght-italic.css'] },
  handwriting: { pkg: '@fontsource-variable/caveat', css: ['wght.css'] },
  display: { pkg: '@fontsource/bebas-neue', css: ['400.css'] },
};

const imports = [];
const entries = [];
for (const [family, { pkg, css }] of Object.entries(FAMILIES)) {
  for (const sheet of css) {
    const text = readFileSync(join(root, 'node_modules', pkg, sheet), 'utf8');
    for (const block of text.match(/@font-face\s*{[^}]*}/g) ?? []) {
      const get = (prop) => block.match(new RegExp(`${prop}:\\s*([^;]+);`))?.[1].trim();
      const file = get('src').match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
      const name = `f${imports.length}`;
      imports.push(`import ${name} from '${pkg}/files/${file}?url';`);
      entries.push(
        `  { family: '${family}', style: '${get('font-style')}', weight: '${get('font-weight')}', ` +
          `unicodeRange: '${get('unicode-range')}', url: ${name} },`,
      );
    }
  }
}

writeFileSync(
  join(root, 'src/render/font-files.ts'),
  `// Generated by scripts/fonts.mjs from the @fontsource packages: do not edit.
${imports.join('\n')}
import type { FontFile } from './fonts';

export const FONT_FILES: FontFile[] = [
${entries.join('\n')}
];
`,
);
console.log(`${entries.length} font files`);
