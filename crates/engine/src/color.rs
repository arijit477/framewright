//! Colour adjustments for media clips: white balance (temperature and tint),
//! brightness, contrast and saturation.
//!
//! Stored as integers from -100 to 100 (0 = unchanged), like other clip
//! settings, so projects compare exactly. How each value maps to pixels is
//! the renderer's job (`apps/web/src/render/color.ts`), shared by every
//! rendering path so preview and export match.

use serde::{Deserialize, Serialize};
use thiserror::Error;

pub const MAX_ADJUSTMENT: i8 = 100;

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", default)]
pub struct ColorAdjust {
    /// Darker (-100) to brighter (100).
    pub brightness: i8,
    /// Flat grey (-100) to strong contrast (100).
    pub contrast: i8,
    /// Black and white (-100) to vivid (100).
    pub saturation: i8,
    /// Cooler, bluer (-100) to warmer, more amber (100).
    pub temperature: i8,
    /// Greener (-100) to more magenta (100).
    pub tint: i8,
}

impl ColorAdjust {
    pub fn is_neutral(&self) -> bool {
        *self == Self::default()
    }

    pub fn validate(&self) -> Result<(), ColorError> {
        for (name, value) in [
            ("brightness", self.brightness),
            ("contrast", self.contrast),
            ("saturation", self.saturation),
            ("temperature", self.temperature),
            ("tint", self.tint),
        ] {
            if !(-MAX_ADJUSTMENT..=MAX_ADJUSTMENT).contains(&value) {
                return Err(ColorError::OutOfRange(name, value));
            }
        }
        Ok(())
    }
}

/// Longest LUT id accepted (ids are generated by the app; this bounds bad input).
pub const MAX_LUT_ID_LENGTH: usize = 64;

/// A colour look-up table applied to a media clip. The table itself is stored
/// with the project (it's large, so it stays out of the timeline); the clip
/// refers to it by id.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LutRef {
    pub lut_id: String,
    /// How strongly the LUT applies: 0 (not at all) to 100 (fully).
    pub intensity_percent: u8,
}

impl LutRef {
    pub fn validate(&self) -> Result<(), ColorError> {
        if self.lut_id.is_empty() || self.lut_id.len() > MAX_LUT_ID_LENGTH {
            return Err(ColorError::LutId);
        }
        if self.intensity_percent > 100 {
            return Err(ColorError::LutIntensity(self.intensity_percent));
        }
        Ok(())
    }
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum ColorError {
    #[error("{0} {1} is out of range (-{MAX_ADJUSTMENT} to {MAX_ADJUSTMENT})")]
    OutOfRange(&'static str, i8),
    #[error("LUT ids must be 1-{MAX_LUT_ID_LENGTH} characters")]
    LutId,
    #[error("LUT intensity {0}% is out of range (0-100%)")]
    LutIntensity(u8),
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_is_neutral_and_valid() {
        assert!(ColorAdjust::default().is_neutral());
        assert_eq!(ColorAdjust::default().validate(), Ok(()));
    }

    #[test]
    fn validates_each_value() {
        let ok = ColorAdjust {
            brightness: -100,
            contrast: 100,
            ..ColorAdjust::default()
        };
        assert_eq!(ok.validate(), Ok(()));
        let bad = ColorAdjust {
            saturation: -101,
            ..ColorAdjust::default()
        };
        assert_eq!(
            bad.validate(),
            Err(ColorError::OutOfRange("saturation", -101))
        );
        let warm = ColorAdjust {
            temperature: 100,
            tint: -100,
            ..ColorAdjust::default()
        };
        assert_eq!(warm.validate(), Ok(()));
        assert!(!warm.is_neutral());
        let bad = ColorAdjust {
            tint: 101,
            ..ColorAdjust::default()
        };
        assert_eq!(bad.validate(), Err(ColorError::OutOfRange("tint", 101)));
    }

    #[test]
    fn lut_refs_are_validated() {
        let lut = |id: &str, intensity_percent| LutRef {
            lut_id: id.to_owned(),
            intensity_percent,
        };
        assert_eq!(lut("abc", 100).validate(), Ok(()));
        assert_eq!(lut("", 50).validate(), Err(ColorError::LutId));
        assert_eq!(lut(&"x".repeat(65), 50).validate(), Err(ColorError::LutId));
        assert_eq!(
            lut("abc", 101).validate(),
            Err(ColorError::LutIntensity(101))
        );
    }

    #[test]
    fn missing_values_are_unchanged() {
        let parsed: ColorAdjust = serde_json::from_str(r#"{"saturation":-100}"#).unwrap();
        assert_eq!((parsed.brightness, parsed.contrast), (0, 0));
        assert_eq!((parsed.temperature, parsed.tint), (0, 0), "older projects");
        assert_eq!(parsed.saturation, -100);
    }
}
